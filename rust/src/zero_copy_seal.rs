//! Zero-copy SEAL event pipeline built on rkyv 0.8 total zero-copy
//! deserialization.
//!
//! High-rate telemetry events are archived with `rkyv::to_bytes` and staged
//! into the SQLite WAL quarantine queue as opaque BLOBs. The daemon consumer
//! accesses them *in place* as [`ArchivedSealEventRecord`] references — fixed
//! pointer offsets plus endianness casting, with **zero heap allocation** and
//! **zero parsing loops**.
//!
//! Fail-closed contract: every untrusted BLOB passes bytecheck validation
//! (`rkyv::access`) *before* any pointer dereference occurs. Corrupted or
//! adversarial buffers are quarantined (status = 2) instead of crashing the
//! real-time actor threads.

use rusqlite::{params, Connection, Result};
use rkyv::{rancor::Error, Archive, Deserialize, Portable, Serialize};

// --- Status transitions for quarantine_queue rows --------------------------
pub const STATUS_QUARANTINED: i64 = 0;
pub const STATUS_SEALED: i64 = 1;
/// Set by the zero-copy validator when an archived BLOB fails bytecheck.
pub const STATUS_ISOLATED: i64 = 2;

/// High-rate telemetry payload structured for zero-copy view access.
///
/// Archived field types follow rkyv's canonical naming (`metric_id` becomes
/// `ArchivedU32`, etc.), so consumers read fields through `to_native()`.
#[derive(Archive, Serialize, Deserialize, Debug, Clone, PartialEq)]
pub struct SealPayload {
    pub metric_id: u32,
    pub cpu_load_ppm: u32,
    pub telemetry_flags: u64,
    pub raw_sensor_stream: Vec<u8>,
}

/// Zero-Copy Archivable Seal Event Record.
///
/// The whole record serializes to one contiguous, cache-friendly binary
/// block — matching the physical layout required for Merkle tree hashing
/// and FRAM/WORM persistence block writes.
#[derive(Archive, Serialize, Deserialize, Debug, Clone, PartialEq)]
pub struct SealEventRecord {
    pub event_id: [u8; 16],              // UUIDv7
    pub timestamp_ns: u64,               // Monotonic crystal tick (STS anchored)
    pub sequence_number: u64,            // Hardware sequence counter
    pub subsystem_id: u16,               // Subsystem identifier
    pub capability_token_hash: [u8; 32], // BLAKE3 hash of active token
    pub payload: SealPayload,            // Nested payload optimized for zero-copy
    pub prev_block_hash: [u8; 32],       // Prior SEAL block hash
    pub signature: [u8; 64],             // Post-quantum signature
}

/// The archived (zero-copy) counterpart of [`SealEventRecord`] — this is the
/// type generated by `#[derive(Archive)]` (canonical name: "Archived" + type).
pub use ArchivedSealEventRecord;
pub struct ZeroCopyQuarantinePipeline;

impl ZeroCopyQuarantinePipeline {
    /// Serializes an event using the rkyv zero-copy archive format and stages
    /// it into the SQLite WAL quarantine queue as a BLOB.
    ///
    /// `event_id`, `timestamp_ns`, and `subsystem_id` are duplicated into
    /// indexed columns so the daemon can route batches without ever opening
    /// the archive envelope.
    pub fn stage_event(conn: &Connection, event: &SealEventRecord) -> Result<()> {
        // Zero-copy serialization into a compact aligned byte buffer.
        let serialized_bytes = rkyv::to_bytes::<Error>(event)
            .map_err(|_| rusqlite::Error::InvalidQuery)?;

        conn.execute(
            "INSERT INTO quarantine_queue
                (event_id, timestamp_ns, subsystem_id, payload_blob, token_hash, status)
             VALUES (?1, ?2, ?3, ?4, ?5, 0)",
            params![
                event.event_id.as_slice(),
                event.timestamp_ns as i64,
                event.subsystem_id as i32,
                serialized_bytes.as_slice(),
                event.capability_token_hash.as_slice(),
            ],
        )?;

        Ok(())
    }

    /// Consumes and inspects quarantined bytes with zero heap deserialization.
    ///
    /// Returns borrowed archived field views into the caller's source buffer;
    /// nothing is copied or allocated.
    pub fn inspect_quarantine_blob<'a>(
        blob_bytes: &'a [u8],
    ) -> Result<ArchivedSealEventRecord, String> {
        // 1. Safe zero-copy validation pass (bytecheck): ensures memory safety
        //    of every relative pointer, length, and enum discriminant before
        //    any pointer cast. Failure here means fail-closed isolation.
        let archived_event =
            rkyv::access::<ArchivedSealEventRecord, Error>(blob_bytes)
                .map_err(|e| format!("Zero-copy validation failed: {e}"))?;

        // 2. Direct field inspection with zero-copy access (no malloc, no
        //    parsing loop) — fixed offsets + endianness casting only.
        let timestamp = archived_event.timestamp_ns.to_native();
        let metric_id = archived_event.payload.metric_id.to_native();

        println!(
            "[ZERO-COPY] Inspected event ID: {:?}, Timestamp: {} ns, Metric ID: {}",
            archived_event.event_id, timestamp, metric_id
        );

        // Nested variable-length slices (like Vec<u8>) are borrowed directly
        // from the source buffer — zero allocation:
        let _stream_slice: &[u8] = archived_event.payload.raw_sensor_stream.as_ref();

        Ok(archived_event)
    }

    /// Fail-closed batch drain for the SealDaemon audit loop: pulls pending
    /// quarantine rows, validates each archived BLOB in place, and either
    /// seals it (status = 1) or isolates it (status = 2).
    ///
    /// Returns the number of records transitioned to SEALED.
    pub fn drain_and_seal(conn: &Connection, max_batch: usize) -> Result<usize> {
        let tx = conn.unchecked_transaction()?;

        let sealed = {
            let mut stmt = tx.prepare(
                "SELECT rowid, payload_blob FROM quarantine_queue
                 WHERE status = 0 LIMIT ?1",
            )?;

            let rows: Vec<(i64, Vec<u8>)> = stmt
                .query_map(params![max_batch.max(1) as i64], |row| {
                    Ok((row.get::<_, i64>(0)?, row.get::<_, Vec<u8>>(1)?))
                })?
                .collect::<Result<_, _>>()?;

            drop(stmt);

            let mut sealed = 0usize;
            for (rowid, blob) in rows.iter() {
                match Self::inspect_quarantine_blob(blob) {
                    Ok(_) => {
                        tx.execute(
                            "UPDATE quarantine_queue SET status = 1 WHERE rowid = ?1",
                            params![rowid],
                        )?;
                        sealed += 1;
                    }
                    Err(e) => {
                        eprintln!(
                            "[ZERO-COPY] FAIL-CLOSED: isolating quarantine row {rowid}: {e}"
                        );
                        tx.execute(
                            "UPDATE quarantine_queue SET status = 2 WHERE rowid = ?1",
                            params![rowid],
                        )?;
                    }
                }
            }
            sealed
        };

        tx.commit()?;
        Ok(sealed)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_event() -> SealEventRecord {
        SealEventRecord {
            event_id: [
                0x01, 0x7f, 0x3a, 0x9c, 0x00, 0x00, 0x00, 0x01, 0x80, 0xaa, 0xbb,
                0xcc, 0xdd, 0xee, 0xff, 0x00,
            ],
            timestamp_ns: 1_730_000_000_123_456_789,
            sequence_number: 42,
            subsystem_id: 7,
            capability_token_hash: [0xab; 32],
            payload: SealPayload {
                metric_id: 9001,
                cpu_load_ppm: 423_111,
                telemetry_flags: 0xDEAD_BEEF_CAFE_F00D,
                raw_sensor_stream: vec![0x01, 0x02, 0x03, 0x04, 0x05],
            },
            prev_block_hash: [0x11; 32],
            signature: [0x99; 64],
        }
    }

    fn open_test_db() -> Connection {
        let conn = Connection::open_in_memory().unwrap();
        conn.execute_batch(
            "PRAGMA journal_mode = WAL;
             CREATE TABLE quarantine_queue (
                 event_id BLOB PRIMARY KEY NOT NULL,
                 timestamp_ns INTEGER NOT NULL,
                 subsystem_id INTEGER NOT NULL,
                 payload_blob BLOB NOT NULL,
                 token_hash BLOB NOT NULL,
                 status INTEGER DEFAULT 0
             );",
        )
        .unwrap();
        conn
    }

    #[test]
    fn zero_copy_roundtrip_and_sqlite_ingress() {
        let event = sample_event();
        let conn = open_test_db();

        // Stage through the WAL quarantine queue as an rkyv archive BLOB.
        ZeroCopyQuarantinePipeline::stage_event(&conn, &event).unwrap();

        // Read the raw BLOB back and validate/inspect it in place.
        let blob: Vec<u8> = conn
            .query_row(
                "SELECT payload_blob FROM quarantine_queue WHERE status = 0",
                [],
                |row| row.get(0),
            )
            .unwrap();

        let archived = ZeroCopyQuarantinePipeline::inspect_quarantine_blob(&blob)
            .expect("valid archive must pass bytecheck");

        // O(1) field access via pointer offsets + endian casts, no parsing.
        assert_eq!(archived.timestamp_ns.to_native(), event.timestamp_ns);
        assert_eq!(archived.sequence_number.to_native(), event.sequence_number);
        assert_eq!(archived.subsystem_id.to_native(), event.subsystem_id);
        assert_eq!(archived.payload.metric_id.to_native(), 9001);
        assert_eq!(archived.payload.cpu_load_ppm.to_native(), 423_111);
        assert_eq!(
            archived.payload.telemetry_flags.to_native(),
            0xDEAD_BEEF_CAFE_F00D
        );
        // Variable-length payload borrowed directly from the source buffer.
        assert_eq!(
            archived.payload.raw_sensor_stream.as_ref(),
            &[0x01, 0x02, 0x03, 0x04, 0x05][..]
        );
        assert_eq!(&archived.signature, &[0x99u8; 64].as_slice());

        // Daemon batch drain seals the verified row.
        let sealed = ZeroCopyQuarantinePipeline::drain_and_seal(&conn, 64).unwrap();
        assert_eq!(sealed, 1);
        let status: i64 = conn
            .query_row("SELECT status FROM quarantine_queue", [], |r| r.get(0))
            .unwrap();
        assert_eq!(status, STATUS_SEALED);
    }

    #[test]
    fn corrupted_blob_fails_closed_into_isolation() {
        let event = sample_event();
        let conn = open_test_db();
        ZeroCopyQuarantinePipeline::stage_event(&conn, &event).unwrap();

        // Simulate bit-rot / adversarial tampering inside the WORM staging
        // buffer: overwrite the root metadata so lengths/pointers are invalid.
        conn.execute(
            "UPDATE quarantine_queue SET payload_blob = ?1",
            params![vec![0xFFu8; 48]],
        )
        .unwrap();

        // Validation must reject the buffer before any dereference.
        let bad = conn
            .query_row("SELECT payload_blob FROM quarantine_queue", [], |r| {
                r.get::<_, Vec<u8>>(0)
            })
            .unwrap();
        assert!(ZeroCopyQuarantinePipeline::inspect_quarantine_blob(&bad).is_err());

        // Batch drain isolates rather than crashes: fail-closed quarantine.
        let sealed = ZeroCopyQuarantinePipeline::drain_and_seal(&conn, 64).unwrap();
        assert_eq!(sealed, 0);
        let status: i64 = conn
            .query_row("SELECT status FROM quarantine_queue", [], |r| r.get(0))
            .unwrap();
        assert_eq!(status, STATUS_ISOLATED);
    }
}
